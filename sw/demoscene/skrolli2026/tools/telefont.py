#!/usr/bin/env python3
"""Cut the telemetry's digits from the display's own font.

Text mode draws the device font at 8x16 screen pixels.  A framebuffer
pixel is 2x2 on screen, so the same glyph drawn pixel for pixel would
be twice the size, and the bar is only 8 framebuffer rows tall.  The
glyph is kept 8 wide and its rows are ORed in pairs, so horizontal
detail survives, no stroke is lost, and a digit fits in 5 rows.

Only rows 2-11 are kept, the digit height.

Output is C: the digits 0-9 then '.', one byte per row, bit 7 leftmost.
"""

import argparse
import sys

GLYPHS = "0123456789."
HEIGHT = 16
TOP, BOTTOM = 2, 12             # rows kept, before pairing
ROWS = (BOTTOM - TOP) // 2


def load(path):
    rows = [int(l, 16) for l in (l.strip() for l in open(path))
            if l and not l.startswith("//")]
    if len(rows) != 256 * HEIGHT:
        sys.exit(f"{path}: {len(rows)} rows, want 256 x {HEIGHT}")
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("font", help="font ROM hex from hw/tools/wsfont2hex.py")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    rows = load(args.font)
    out = [
        "/* Generated by tools/telefont.py from the display font; do not edit. */",
        "",
        f"const unsigned char rt_telefont[{len(GLYPHS)}][{ROWS}] = {{",
    ]
    for ch in GLYPHS:
        g = rows[ord(ch) * HEIGHT:(ord(ch) + 1) * HEIGHT]
        cut = ", ".join(f"0x{g[r] | g[r + 1]:02X}" for r in range(TOP, BOTTOM, 2))
        out.append(f"    {{ {cut} }},   /* {ch} */")
    out.append("};")

    with open(args.output, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
