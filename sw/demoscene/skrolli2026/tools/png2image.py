#!/usr/bin/env python3
"""Compile an indexed PNG into the rt_image_t runtime/rt.h describes.

Takes colour type 3 (indexed) at any bit depth, non-interlaced; the
pixels come out one byte per pixel.  The palette entries 248-255 belong
to the telemetry bar, so a pixel using one is an error, and at most 248
entries are kept.  Rows are padded to whole words with index 0, so an
aligned row copies to the framebuffer a word at a time.

Writes <name>_image.c, with the pixels in .payload (bulk data has to
sit past .data, see runtime/demo.ld), and <name>_image.h declaring
<name>_image and its size as <NAME>_IMAGE_W and <NAME>_IMAGE_H.
"""

import argparse
import os
import re
import struct
import sys
import zlib

RESERVED = 248                  # RT_PAL_RESERVED: parts own 0..247
SIGNATURE = b"\x89PNG\r\n\x1a\n"


class ImageError(Exception):
    pass


def read_png(data):
    if not data.startswith(SIGNATURE):
        raise ImageError("not a PNG file")
    pos, ihdr, palette, idat = len(SIGNATURE), None, None, []
    while pos < len(data):
        if pos + 8 > len(data):
            raise ImageError("truncated chunk header")
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if len(body) != length:
            raise ImageError(f"truncated {kind.decode(errors='replace')} chunk")
        pos += 12 + length
        if kind == b"IHDR":
            ihdr = struct.unpack(">IIBBBBB", body)
        elif kind == b"PLTE":
            palette = [tuple(body[i:i + 3]) for i in range(0, length, 3)]
        elif kind == b"IDAT":
            idat.append(body)
        elif kind == b"IEND":
            break

    if ihdr is None:
        raise ImageError("no IHDR chunk")
    w, h, depth, colour, _, _, interlace = ihdr
    if colour != 3:
        raise ImageError(f"colour type {colour}, not indexed; export it as 8-bit indexed")
    if depth not in (1, 2, 4, 8):
        raise ImageError(f"bit depth {depth} is not valid for an indexed PNG")
    if interlace:
        raise ImageError("interlaced; export it without interlacing")
    if not palette:
        raise ImageError("indexed but has no PLTE chunk")

    raw = zlib.decompress(b"".join(idat))
    row_bytes = (w * depth + 7) // 8
    if len(raw) != h * (row_bytes + 1):
        raise ImageError(f"pixel data is {len(raw)} bytes, want {h * (row_bytes + 1)}")

    pixels, prev = [], bytearray(row_bytes)
    for y in range(h):
        kind = raw[y * (row_bytes + 1)]
        row = bytearray(raw[y * (row_bytes + 1) + 1:(y + 1) * (row_bytes + 1)])
        for i in range(row_bytes):
            left = row[i - 1] if i else 0
            up, up_left = prev[i], prev[i - 1] if i else 0
            if kind == 0:
                pred = 0
            elif kind == 1:
                pred = left
            elif kind == 2:
                pred = up
            elif kind == 3:
                pred = (left + up) // 2
            elif kind == 4:
                p = left + up - up_left
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - up_left)
                pred = left if pa <= pb and pa <= pc else up if pb <= pc else up_left
            else:
                raise ImageError(f"row {y} has unknown filter {kind}")
            row[i] = (row[i] + pred) & 0xFF
        prev = row
        per_byte = 8 // depth
        pixels.append([(row[x // per_byte] >> (8 - depth * (x % per_byte + 1))) & ((1 << depth) - 1)
                       for x in range(w)])
    return w, h, palette, pixels


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("png")
    ap.add_argument("-o", "--output", required=True, help="the .c; the .h goes beside it")
    args = ap.parse_args()

    name = os.path.splitext(os.path.basename(args.png))[0]
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", name):
        sys.exit(f"{args.png}: the name must be a C identifier in lower case")

    try:
        with open(args.png, "rb") as f:
            w, h, palette, pixels = read_png(f.read())
        for y, row in enumerate(pixels):
            for x, i in enumerate(row):
                if i >= len(palette):
                    raise ImageError(f"pixel {x},{y} is index {i}, past the {len(palette)}-entry palette")
                if i >= RESERVED:
                    raise ImageError(f"pixel {x},{y} is index {i}; {RESERVED}-255 belong to the telemetry bar")
    except (ImageError, zlib.error) as e:
        sys.exit(f"{args.png}: {e}")

    stride = (w + 3) & ~3
    colours = palette[:RESERVED]
    upper = name.upper()
    base = os.path.splitext(args.output)[0]

    with open(base + ".h", "w") as f:
        f.write(f"/* Generated by tools/png2image.py from {args.png}; do not edit. */\n\n"
                f"#define {upper}_IMAGE_W  {w}\n"
                f"#define {upper}_IMAGE_H  {h}\n\n"
                f"extern const rt_image_t {name}_image;\n")

    body = bytearray()
    for row in pixels:
        body += bytes(row) + bytes(stride - w)
    pix = ",\n".join("    " + ",".join(str(b) for b in body[i:i + 32])
                     for i in range(0, len(body), 32))
    pal = ",\n".join("    " + ", ".join(f"0x{r:02X}{g:02X}{b:02X}" for r, g, b in colours[i:i + 6])
                     for i in range(0, len(colours), 6))
    with open(args.output, "w") as f:
        f.write(f"/* Generated by tools/png2image.py from {args.png}; do not edit. */\n\n"
                '#include "rt.h"\n\n'
                f"static const uint32_t palette[{len(colours)}] = {{\n{pal}\n}};\n\n"
                f"__attribute__((section(\".payload\"), aligned(16)))\n"
                f"static const uint8_t pixels[{len(body)}] = {{\n{pix}\n}};\n\n"
                f"const rt_image_t {name}_image = {{ {w}, {h}, {stride}, {len(colours)}, palette, pixels }};\n")


if __name__ == "__main__":
    main()
