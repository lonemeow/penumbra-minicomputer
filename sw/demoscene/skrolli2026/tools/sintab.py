#!/usr/bin/env python3
"""Generate the sine table runtime/trig.h looks up.

One full turn in STEPS entries of Q14 (1.0 = 16384, exact), each the
sine at its step rounded to nearest.  Q14 rather than 16.16: at 1024
steps the angle's own rounding costs up to 0.003, and storing more than
14 fraction bits would only store that error more precisely.
"""

import argparse
import math

STEPS = 1024
ONE = 1 << 14


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    values = [round(math.sin(2 * math.pi * i / STEPS) * ONE) for i in range(STEPS)]
    rows = ",\n".join("    " + ", ".join(f"{v:6d}" for v in values[i:i + 8])
                      for i in range(0, STEPS, 8))
    with open(args.output, "w") as f:
        f.write("/* Generated by tools/sintab.py; do not edit. */\n\n"
                '#include "rt.h"\n\n'
                "_Static_assert(RT_SIN_STEPS == %d, \"tools/sintab.py and trig.h agree\");\n\n"
                "RT_PINNED_CONST const int16_t rt_sintab[RT_SIN_STEPS] = {\n%s\n};\n"
                % (STEPS, rows))


if __name__ == "__main__":
    main()
