#ifndef LLVM_LIB_TARGET_PENUMBRA_PENUMBRASUBTARGET_H
#define LLVM_LIB_TARGET_PENUMBRA_PENUMBRASUBTARGET_H

#include "GISel/PenumbraCallLowering.h"
#include "GISel/PenumbraLegalizerInfo.h"
#include "GISel/PenumbraRegisterBankInfo.h"
#include "PenumbraFrameLowering.h"
#include "PenumbraISelLowering.h"
#include "PenumbraInstrInfo.h"
#include "PenumbraRegisterInfo.h"
#include "llvm/CodeGen/GlobalISel/CallLowering.h"
#include "llvm/CodeGen/GlobalISel/InlineAsmLowering.h"
#include "llvm/CodeGen/GlobalISel/InstructionSelector.h"
#include "llvm/CodeGen/GlobalISel/LegalizerInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"

#define GET_SUBTARGETINFO_HEADER
#include "PenumbraGenSubtargetInfo.inc"

namespace llvm {

class PenumbraSubtarget : public PenumbraGenSubtargetInfo {
  // Storage for the tuning features declared in Penumbra.td, written by
  // ParseSubtargetFeatures from the tune name and any -mattr string.  The
  // expansion is empty while no feature is declared.
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "PenumbraGenSubtargetInfo.inc"

  // RegInfo must be declared before InstrInfo — InstrInfo constructor needs TRI.
  PenumbraRegisterInfo RegInfo;
  PenumbraInstrInfo InstrInfo;
  PenumbraFrameLowering FrameLowering;
  PenumbraISelLowering TLInfo;
  PenumbraLegalizerInfo Legalizer;
  PenumbraRegisterBankInfo RegBankInfo;
  std::unique_ptr<CallLowering> CallLoweringInfo;
  std::unique_ptr<InlineAsmLowering> InlineAsmLoweringInfo;
  std::unique_ptr<InstructionSelector> InstSelector;

public:
  // The tuning target chosen when neither -mcpu nor -mtune names one: the
  // answer that runs acceptably on every generation, since a module that
  // says nothing about its target may be linked into anything.
  static constexpr StringLiteral DefaultCPU = "generic";

  // Resolve a possibly-empty -mcpu / -mtune name to a real processor.  Both
  // the MCSubtargetInfo base and the TargetMachine's per-function lookup
  // resolve through these, so "unspecified" means one thing everywhere.
  static StringRef resolveCPU(StringRef CPU) {
    return CPU.empty() ? StringRef(DefaultCPU) : CPU;
  }
  // An absent -mtune follows -mcpu, matching every other target's reading of
  // "tune for what I am building for unless told otherwise".
  static StringRef resolveTuneCPU(StringRef CPU, StringRef TuneCPU) {
    return TuneCPU.empty() ? resolveCPU(CPU) : TuneCPU;
  }

  PenumbraSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                    StringRef FS, const TargetMachine &TM);

  // Set the feature fields above from the resolved names.  Returns *this so
  // the constructor can sequence it ahead of the members that read them.
  PenumbraSubtarget &initializeSubtargetDependencies(StringRef CPU,
                                                     StringRef TuneCPU,
                                                     StringRef FS);

  // Parses features string setting specified subtarget options.  The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  // Predicate accessors for the tuning features (`hasSomeProperty()`).
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool GETTER() const { return ATTRIBUTE; }
#include "PenumbraGenSubtargetInfo.inc"

  const PenumbraInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const PenumbraFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const PenumbraRegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }
  const PenumbraISelLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const RegisterBankInfo *getRegBankInfo() const override {
    return &RegBankInfo;
  }
  const LegalizerInfo *getLegalizerInfo() const override {
    return &Legalizer;
  }
  const CallLowering *getCallLowering() const override {
    return CallLoweringInfo.get();
  }
  const InlineAsmLowering *getInlineAsmLowering() const override {
    return InlineAsmLoweringInfo.get();
  }
  InstructionSelector *getInstructionSelector() const override {
    return InstSelector.get();
  }
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_PENUMBRA_PENUMBRASUBTARGET_H
